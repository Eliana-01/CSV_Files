    private void DeleteActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_DeleteActionPerformed
        // TODO add your handling code here:
        int SelectedRow = jTable1.getSelectedRow();
        if (SelectedRow == -1){
            JOptionPane.showMessageDialog(null, "Please select a row from the table", "No Row Selected", JOptionPane.WARNING_MESSAGE);
            return;
        }
        Object indexValue = jTable1.getValueAt(SelectedRow, 0);
        String indexSearch = indexValue.toString();
        this.manage.delete(indexSearch, "");
        this.manage.printTable(jTable1);
    }//GEN-LAST:event_DeleteActionPerformed

